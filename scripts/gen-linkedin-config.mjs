#!/usr/bin/env node
/**
 * gen-linkedin-config.mjs
 *
 * Reads the exported profile JSON (from the JobOps UI "Export profile" button
 * or piped from stdin) and writes all four Python config files that
 * Auto_job_applier_linkedIn needs into the target directory.
 *
 * Usage:
 *   node scripts/gen-linkedin-config.mjs profile.json ../Auto_job_applier_linkedIn
 *   cat profile.json | node scripts/gen-linkedin-config.mjs - ../Auto_job_applier_linkedIn
 */

import fs   from "fs";
import path from "path";

// ─── Read args ────────────────────────────────────────────────────────────────
const [,, profileArg, targetArg] = process.argv;

if (!profileArg || !targetArg) {
  console.error("Usage: node scripts/gen-linkedin-config.mjs <profile.json|-> <bot-dir>");
  process.exit(1);
}

const raw    = profileArg === "-" ? fs.readFileSync("/dev/stdin", "utf8") : fs.readFileSync(profileArg, "utf8");
const target = path.resolve(targetArg, "config");
const profile = JSON.parse(raw);

fs.mkdirSync(target, { recursive: true });
fs.mkdirSync(path.resolve(targetArg, "all resumes", "default"), { recursive: true });
fs.mkdirSync(path.resolve(targetArg, "all excels"), { recursive: true });
fs.mkdirSync(path.resolve(targetArg, "logs"), { recursive: true });

// ─── Helpers ──────────────────────────────────────────────────────────────────
const py  = (v) => JSON.stringify(v);                       // Python string literal
const pyL = (arr) => `[${arr.map(py).join(", ")}]`;        // Python list literal
const pyB = (b) => b ? "True" : "False";                   // Python bool

function write(file, content) {
  fs.writeFileSync(path.join(target, file), content, "utf8");
  console.log(`  ✓ config/${file}`);
}

// ─── Shortcuts into profile ───────────────────────────────────────────────────
const p   = profile.personal ?? {};
const sp  = profile.search   ?? {};
const aa  = profile.autoApply ?? {};
const exp = profile.experience ?? [];
const sk  = profile.skills ?? [];

const keywords  = sp.keywords         ?? [];
const locations = sp.locations        ?? [];
const jobTypes  = sp.jobTypes         ?? [];
const expLevels = sp.experienceLevels ?? [];
const salaryMin = sp.salaryMin        ?? 0;

// Map our job-type labels → LinkedIn's filter strings
const JOB_TYPE_MAP = {
  "full-time": "Full-time", "part-time": "Part-time",
  contract: "Contract",     internship: "Internship",
  temporary: "Temporary",   volunteer: "Volunteer",
  other: "Other",
};
const EXP_LEVEL_MAP = {
  internship: "Internship",     entry: "Entry level",
  associate: "Associate",       mid: "Mid-Senior level",
  director: "Director",         executive: "Executive",
};

const liJobTypes  = jobTypes.map((t) => JOB_TYPE_MAP[t] ?? t);
const liExpLevels = expLevels.map((e) => EXP_LEVEL_MAP[e] ?? e);

// Salary string LinkedIn understands (nearest bracket)
function salaryBracket(min) {
  const BRACKETS = [40000, 60000, 80000, 100000, 120000, 140000, 160000, 180000, 200000];
  const match = BRACKETS.filter((b) => b <= min).pop();
  return match ? `$${(match / 1000).toFixed(0)},000+` : "";
}

// Years of experience from first job entry
const yearsExp = exp.length > 0 && exp[0].startDate
  ? Math.max(1, new Date().getFullYear() - new Date(exp[0].startDate).getFullYear())
  : 3;

// Most recent employer
const recentEmployer = exp.length > 0 ? (exp[0].employer ?? "Not Applicable") : "Not Applicable";

// ─── secrets.py ──────────────────────────────────────────────────────────────
write("secrets.py", `# Auto-generated by gen-linkedin-config.mjs — do not edit by hand
# Add your LinkedIn credentials and optional AI key below.

username = ""          # ← your LinkedIn email
password = ""          # ← your LinkedIn password

use_AI = False         # Set True to enable AI answer generation
ai_provider = "openai" # "openai" | "gemini" | "ollama"
openai_api_key = ""
gemini_api_key = ""
ollama_api_url = "http://localhost:11434"
ollama_model   = "llama3"
`);

// ─── personals.py ─────────────────────────────────────────────────────────────
const nameParts = (p.fullName ?? "").trim().split(/\s+/);
write("personals.py", `# Auto-generated by gen-linkedin-config.mjs
first_name  = ${py(nameParts[0] ?? "")}
middle_name = ${py(nameParts.length === 3 ? nameParts[1] : "")}
last_name   = ${py(nameParts[nameParts.length - 1] ?? "")}

phone_number  = ${py(p.phone ?? "")}
current_city  = ${py(p.location ?? "")}
street        = ${py(p.street ?? "")}
state         = ${py(p.state ?? "")}
zipcode       = ${py((sp.zipCodes ?? [])[0] ?? p.zipcode ?? "")}
country       = ${py(p.country ?? "United States")}

ethnicity         = "Decline"
gender            = "Decline"
disability_status = "Decline"
veteran_status    = "Decline"
`);

// ─── search.py ───────────────────────────────────────────────────────────────
write("search.py", `# Auto-generated by gen-linkedin-config.mjs
search_terms     = ${pyL(keywords.length ? keywords : ["Software Engineer"])}
search_location  = ${py(locations[0] ?? "United States")}
switch_number    = 30
randomize_search_order = False

sort_by     = "Most recent"
date_posted = "Past week"
salary      = ${py(salaryBracket(salaryMin))}

easy_apply_only  = True
experience_level = ${pyL(liExpLevels)}
job_type         = ${pyL(liJobTypes)}
on_site          = ${pyL(sp.remoteOnly ? ["Remote"] : ["On-site", "Hybrid", "Remote"])}

companies      = []
location       = ${pyL(locations)}
industry       = []
job_function   = []
job_titles     = []
benefits       = []
commitments    = []

under_10_applicants  = False
in_your_network      = False
fair_chance_employer = False

pause_after_filters = False

about_company_bad_words  = ${pyL(sp.blacklistedKeywords ?? [])}
about_company_good_words = []
bad_words                = ${pyL(sp.blacklistedKeywords ?? [])}

security_clearance  = False
did_masters         = False
current_experience  = ${yearsExp}
`);

// ─── questions.py ─────────────────────────────────────────────────────────────
const customAnswerMap = Object.fromEntries(
  (aa.customAnswers ?? []).map(({ question, answer }) => [question.toLowerCase(), answer])
);
const getAnswer = (key) => customAnswerMap[key] ?? "";

write("questions.py", `# Auto-generated by gen-linkedin-config.mjs
default_resume_path = "all resumes/default/resume.pdf"

years_of_experience = "${yearsExp}"
require_visa        = "${sp.requireVisaSupport ? "Yes" : "No"}"

portfolio   = ${py(p.website ?? p.portfolio ?? "")}
linkedin    = ${py(p.linkedin ?? "")}
github      = ${py(p.github ?? "")}
website     = ${py(p.website ?? "")}

citizenship = ${py(getAnswer("citizenship") || "Will provide details")}
desired_salary   = ${salaryMin || 80000}
current_salary   = ${getAnswer("current salary") || 0}
notice_period    = ${getAnswer("notice period") || 30}

recent_employer   = ${py(recentEmployer)}
confidence_level  = "8"

headline = ${py(p.headline ?? `${sk.slice(0, 3).join(", ")} professional`)}
summary  = ${py(p.summary ?? "")}
cover_letter_content = "I am excited to apply for this role and believe my skills are a strong match."

${(aa.customAnswers ?? []).map(({ question, answer }) =>
  `# Q: ${question}\n# A: ${answer}`
).join("\n")}

pause_before_submit        = True
pause_at_failed_question   = True
overwrite_previous_answers = False
`);

// ─── settings.py ──────────────────────────────────────────────────────────────
write("settings.py", `# Auto-generated by gen-linkedin-config.mjs
close_tabs          = False
follow_companies    = False
run_non_stop        = False
alternate_sortby    = True
cycle_date_posted   = True
stop_date_cycle_at_24hr = True

generated_resume_path = "all resumes/"
file_name        = "all excels/all_applied_applications_history.csv"
failed_file_name = "all excels/all_failed_applications_history.csv"
logs_folder_path = "logs/"

click_gap         = 1
run_in_background = False
disable_extensions = False
safe_mode         = True
smooth_scroll     = False
keep_screen_awake = True
stealth_mode      = True
showAiErrorAlerts = False
`);

console.log(`
Done! Config files written to: ${target}

Next steps:
  1. Open config/secrets.py and add your LinkedIn credentials
  2. Copy your resume PDF to:  ${path.resolve(targetArg, "all resumes", "default", "resume.pdf")}
  3. Run the bot:              python runAiBot.py
`);
